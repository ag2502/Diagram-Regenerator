def test_dbml():
    text = render_dbml(shop_schema())
    assert "Enum mood {\n  sad\n  ok\n}" in text
    assert "Table customers [note: 'People who buy things.'] {" in text
    assert "  id bigint [pk, increment]" in text
    assert "  email varchar(255) [not null, unique, note: 'Login \"email\"']" in text
    assert "  balance numeric(10,2) [default: 0]" in text
    assert "  status text [default: 'new']" in text
    assert '  "note | pipe" text' in text
    assert "Table billing.invoices {" in text
    assert "    (order_id, line) [pk]" in text
    assert "Ref: orders.customer_id > customers.id [delete: cascade]" in text
    assert "Ref: billing.invoices.order_id - orders.id" in text


def test_html_is_self_contained_and_escaped():
    schema = shop_schema()
    schema.tables["customers"].comment = "<script>alert(1)</script>"
    page = render_html(schema, title="Shop", source="db")
    assert page.startswith("<!doctype html>")
    assert "&lt;script&gt;alert(1)&lt;/script&gt;" in page
    assert "<script>alert(1)" not in page
    payload = page.split('<script type="application/json" id="diagrams">')[1].split("</script>")[0]
    data = json.loads(payload)
    assert set(data["focus"]) == set(schema.tables)
    assert_valid_mermaid_er(data["overview"])
    for diagram in data["focus"].values():
        assert_valid_mermaid_er(diagram)


def test_render_dispatch_and_format_detection():
    schema = shop_schema()
    assert render(schema, "json") == schema.to_json()
    assert render(schema, "mmd").startswith("erDiagram")
    assert render(schema, "md").startswith("<!--")
    assert format_for_path("docs/SCHEMA.md") == "markdown"
    assert format_for_path("schema/schema.json") == "json"
    assert format_for_path("x.dbml") == "dbml"
    with pytest.raises(ValueError):
        format_for_path("x.png")
    with pytest.raises(ValueError):
        render(schema, "png")
